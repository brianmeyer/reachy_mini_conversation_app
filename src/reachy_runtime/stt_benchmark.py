def summarize_records(records: list[dict[str, Any]]) -> list[dict[str, Any]]:
    groups: dict[tuple[str, str, str, str], list[dict[str, Any]]] = defaultdict(list)
    for record in records:
        key = (
            str(record.get("model", "")),
            str(record.get("device", "")),
            str(record.get("compute_type", "")),
            str(record.get("phrase_id", "")),
        )
        groups[key].append(record)

    summaries: list[dict[str, Any]] = []
    for (model, device, compute_type, phrase_id), items in sorted(groups.items()):
        ok_items = [item for item in items if item.get("ok")]
        tx_ms = [float(item["transcribe_ms"]) for item in ok_items if item.get("transcribe_ms") is not None]
        load_ms = [float(item["load_ms"]) for item in items if item.get("load_ms") is not None]
        summaries.append(
            {
                "model": model,
                "device": device,
                "compute_type": compute_type,
                "phrase_id": phrase_id,
                "count": len(items),
                "success": len(ok_items),
                "load_ms": _round_or_none(load_ms[0] if load_ms else None),
                "transcribe_p50_ms": _round_or_none(percentile(tx_ms, 0.50)),
                "transcribe_p95_ms": _round_or_none(percentile(tx_ms, 0.95)),
                "languages": sorted(
                    {str(item.get("detected_language")) for item in ok_items if item.get("detected_language")}
                ),
                "texts": [str(item.get("text")) for item in ok_items if item.get("text")][:2],
                "errors": sorted({str(item.get("error")) for item in items if item.get("error")})[:3],
                "skipped": all(item.get("skipped") for item in items),
            }
        )
    return summaries


def make_markdown_report(results: dict[str, Any]) -> str:
    summaries = summarize_records(results.get("records", []))
    lines = [
        "# Reachy Jetson STT Benchmark",
        "",
        f"Generated: {results.get('generated_at', 'unknown')}",
        "",
        "## Summary",
        "",
    ]
    policy = results.get("resource_policy") or {}
    if policy:
        decision = policy.get("decision", {})
        lines.append(
            "- Resource policy: "
            f"{decision.get('severity', 'unknown')} "
            f"(GPU STT={'yes' if decision.get('allow_gpu_stt') else 'no'})"
        )
    if not summaries:
        lines.append("- No benchmark records were produced.")
    for item in summaries:
        if item["skipped"]:
            reason = item["errors"][0] if item["errors"] else "skipped"
            lines.append(
                f"- {item['model']} {item['device']}/{item['compute_type']} {item['phrase_id']}: skipped ({reason})"
            )
            continue
        status = f"{item['success']}/{item['count']} ok"
        lines.append(
            "- "
            f"{item['model']} {item['device']}/{item['compute_type']} {item['phrase_id']}: {status}, "
            f"load={item['load_ms']}ms, "
            f"transcribe p50/p95={_fmt_ms(item['transcribe_p50_ms'])}/{_fmt_ms(item['transcribe_p95_ms'])}, "
            f"detected={','.join(item['languages']) or 'unknown'}"
        )
        if item["texts"]:
            lines.append(f"  Text sample: {item['texts'][0]!r}")
        if item["errors"]:
            lines.append(f"  Error sample: {item['errors'][0]}")

    lines.extend(
        [
            "",
            "## Notes",
            "",
            "- Synthetic WAVs are generated by the current Jetson TTS stack; real mic/kid audio still needs a separate live capture pass.",
            "- English-only `.en` Whisper models are intentionally excluded from the product benchmark.",
            "",
            "## Raw JSON",
            "",
            "```json",
            _json_dump(results),
            "```",
            "",
        ]
    )
    return "\n".join(lines)


def _round_or_none(value: float | None) -> float | None:
    return round(value, 1) if value is not None else None


def _fmt_ms(value: float | None) -> str:
    return "unavailable" if value is None else f"{value}ms"


def _json_dump(value: Any) -> str:
    import json

    return json.dumps(value, indent=2, ensure_ascii=False, default=str)[:60_000]
